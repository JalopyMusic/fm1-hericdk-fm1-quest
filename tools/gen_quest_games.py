"""FM Hero and Piano covers (the title pictures of the two games), 240 x 240, 1 bit, in two LZ4 halves (240 x 120 each, 30 bytes a row, bit 7 = left).
Source: assets/quest/games/fm-hero.gif and piano-hero.gif.   tools/gen_quest_games.py build/gen/felucca_qgames.h"""
import sys
from pathlib import Path
from PIL import Image
sys.path.insert(0, str(Path(__file__).resolve().parent))
import lz4blk
R = Path(__file__).resolve().parents[1] / "assets" / "quest" / "games"
L = ["/* generated by tools/gen_quest_games.py */", "#pragma once", "#include <stdint.h>"]
tot = 0
for name, key in (("fm-hero", "FM"), ("piano-hero", "PIANO")):
    im = Image.open(R / (name + ".gif")).convert("L").resize((240, 240), Image.LANCZOS).point(lambda v: 255 if v > 127 else 0).convert("1")
    raw = im.tobytes()                                   # 30 bytes a row, 1 = white
    for half in (0, 1):
        z = lz4blk.compress(raw[half * 3600:(half + 1) * 3600])
        tot += len(z)
        L.append(f"static const uint8_t QCOVER_{key}_{half}[{len(z)}] = {{" + ",".join(str(b) for b in z) + "};")
Path(sys.argv[1]).write_text("\n".join(L) + "\n")
print(f"quest games: covers {tot} B")
