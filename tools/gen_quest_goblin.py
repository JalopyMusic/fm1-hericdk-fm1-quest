"""The two goblins (archer, axe) of the boss scene, a lean cut of the Zneeke "goblin scout v5" silhouette pack (assets/quest/goblin/*.png, 64 x 64 frames, one
animation a row). Each goblin: 22 frames - idle 4, run 4, attack 8, death 6 - cropped to the box that holds them all, 4 symbols (clear, dark, grey, light), every
frame coded alone with a binary range coder (LZMA style, 11-bit probabilities, shift 5; the context is the pixel to the left and the one above).
tools/gen_quest_goblin.py build/gen/felucca_qgob.h"""
import sys
from pathlib import Path
from PIL import Image
A = Path(__file__).resolve().parents[1] / "assets" / "quest" / "goblin"
# kind: (png, [(row, [frame columns]) for idle, run, attack, death])
KINDS = [
    ("goblin_scout_v5_bow_silhouette.png", [(0, [0, 2, 4, 6]), (3, [0, 2, 4, 6]), (2, [0, 3, 6, 9, 12, 15, 18, 21]), (5, [0, 3, 6, 9, 12, 15])]),
    ("goblin_scout_v5_weapons_axe_silhouette.png", [(4, [0, 2, 4, 6]), (6, [0, 2, 4, 6]), (8, [0, 1, 2, 3, 4, 5, 6, 7]), (16, [0, 2, 4, 6, 8, 11])]),
]

class Enc:
    def __init__(s): s.low = 0; s.range = 0xFFFFFFFF; s.cache = 0; s.cache_size = 1; s.out = bytearray()
    def shift_low(s):
        if s.low < 0xFF000000 or s.low >= (1 << 32):
            carry = s.low >> 32
            temp = s.cache
            while True:
                s.out.append((temp + carry) & 0xFF); temp = 0xFF
                s.cache_size -= 1
                if s.cache_size == 0: break
            s.cache = (s.low >> 24) & 0xFF
        s.cache_size += 1
        s.low = (s.low & 0x00FFFFFF) << 8
    def bit(s, probs, i, b):
        p = probs[i]; bound = (s.range >> 11) * p
        if b == 0: s.range = bound; probs[i] = p + ((2048 - p) >> 5)
        else: s.low += bound; s.range -= bound; probs[i] = p - (p >> 5)
        while s.range < (1 << 24): s.range = (s.range << 8) & 0xFFFFFFFF; s.shift_low()
    def finish(s):
        for _ in range(5): s.shift_low()
        return bytes(s.out)

def sym(p):                       # 0 clear, 1 dark, 2 grey, 3 light
    if p[3] < 128: return 0
    l = (p[0] * 3 + p[1] * 6 + p[2]) / 10
    return 1 if l < 90 else 2 if l < 200 else 3

def encode(f, W, H):
    e = Enc(); pr = [1024] * 48
    for y in range(H):
        for x in range(W):
            l = f[y * W + x - 1] if x else 0
            u = f[(y - 1) * W + x] if y else 0
            c = (l * 4 + u) * 3
            v = f[y * W + x]
            e.bit(pr, c, 0 if v == 0 else 1)
            if v:
                e.bit(pr, c + 1, 0 if v == 1 else 1)
                if v > 1: e.bit(pr, c + 2, 0 if v == 2 else 1)
    return e.finish()

if not all((A / png).exists() for png, _ in KINDS):          # the source pack (Zneeke's goblin scout v5) is not redistributed: the repository keeps the generated data
    pre = A / "qgob.prebuilt.h"
    if not pre.exists():
        raise SystemExit("assets/quest/goblin: neither the source PNGs nor qgob.prebuilt.h are here")
    Path(sys.argv[1]).write_text(pre.read_text())
    print("quest goblin: prebuilt data (the source pack is not in the repository)")
    raise SystemExit(0)
blob, fo, dims, anims = bytearray(), [], [], []
for png, plan in KINDS:
    im = Image.open(A / png).convert("RGBA")
    frames = []
    for row, cols in plan:
        for c in cols:
            frames.append(im.crop((c * 64, row * 64, c * 64 + 64, row * 64 + 64)))
    x0 = min(f.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox()[0] for f in frames)
    y0 = min(f.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox()[1] for f in frames)
    x1 = max(f.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox()[2] for f in frames)
    y1 = max(f.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox()[3] for f in frames)
    W, H = x1 - x0, y1 - y0
    dims.append((W, H))
    offs = [len(blob)]
    for f in frames:
        px = [sym(p) for p in f.crop((x0, y0, x1, y1)).getdata()]
        blob += encode(px, W, H)
        offs.append(len(blob))
    fo.append(offs)
L = ["/* generated by tools/gen_quest_goblin.py */", "#pragma once", "#include <stdint.h>",
     "#define QGOB_N 22   /* idle 0..3, run 4..7, attack 8..15, death 16..21 */",
     "static const uint8_t QGOB_W[2] = {%d,%d}, QGOB_H[2] = {%d,%d};" % (dims[0][0], dims[1][0], dims[0][1], dims[1][1]),
     "static const uint16_t QGOB_FO[2][23] = {" + ",".join("{" + ",".join(map(str, o)) + "}" for o in fo) + "};",
     f"static const uint8_t QGOB_Z[{len(blob)}] = {{" + ",".join(map(str, blob)) + "};"]
Path(sys.argv[1]).write_text("\n".join(L) + "\n")
print(f"quest goblin: {len(blob)} B, boxes {dims}")
