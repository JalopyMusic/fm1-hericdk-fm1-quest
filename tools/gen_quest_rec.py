"""FM1 Quest REC picture: assets/quest/rec-crt.png (the campfire, any size, square) reduced to 120 x 120, the band rows 24..85 (124 screen rows once doubled)
quantized to the 16 Quest colours with a 4x4 ordered dither, 4 bits a pixel (2.5 KB). Without the file the header says height 0 and the REC screen keeps the camp drawn by code.
tools/gen_quest_rec.py build/gen/felucca_qrec.h"""
import sys
from pathlib import Path
A = Path(__file__).resolve().parents[1] / "assets" / "quest" / "rec-crt.png"
PAL = ["1a1016", "2b2338", "5a3050", "2f4a3a", "6a4030", "4a3c48", "a89aa0", "f2e2c4", "c8443c", "e08a3c", "f0c860", "6a9a4a", "4a78b0", "8a6a9a", "e09090", "f0b890"]
PAL = [tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) for h in PAL]
BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5]
W, Y0, H = 120, 24, 62
out = Path(sys.argv[1])
if not A.exists():
    out.write_text("/* generated by tools/gen_quest_rec.py: no assets/quest/rec-crt.png, the REC screen keeps the camp drawn by code */\n#pragma once\n#include <stdint.h>\n#define QREC_W 120\n#define QREC_H 0\nstatic const uint8_t QREC_Z[1] = {0}, QREC_PAL[1] = {0}, QREC_FZ[1] = {0};\n#define QREC_N 1\n#define QREC_NF 0\n#define QREC_FX 0\n#define QREC_FW 1\n#define QREC_FY 0\n#define QREC_FH 1\nstatic const uint16_t QREC_FO[1] = {0};\n")
    print("quest rec: no picture (the camp stays procedural)")
    raise SystemExit(0)
from PIL import Image
# 6 of the 16 Quest colours (the filters recolour them): black, dark and light grey, bone, orange, yellow (the fire)
USE = [0, 5, 6, 7, 9, 10]
N = len(USE)
im = Image.open(A).convert("RGB").resize((W, W), Image.LANCZOS)
px = im.load()
idx = []
for y in range(Y0, Y0 + H):
    for x in range(W):
        th = (BAYER[(y % 4) * 4 + x % 4] / 16 - 0.5) * 40
        c = px[x, y]
        r, g, b = (c[i] + th for i in range(3))
        idx.append(min(range(N), key=lambda j: (r - PAL[USE[j]][0]) ** 2 * .3 + (g - PAL[USE[j]][1]) ** 2 * .59 + (b - PAL[USE[j]][2]) ** 2 * .11))
try:
    pv = Image.new("RGB", (W, H)); pv.putdata([PAL[USE[i]] for i in idx]); pv.resize((W * 4, H * 4), Image.NEAREST).save(Path(sys.argv[1]).with_suffix(".png"))
except Exception:
    pass

class Enc:
    def __init__(s): s.low = 0; s.range = 0xFFFFFFFF; s.cache = 0; s.cache_size = 1; s.out = bytearray()
    def shift_low(s):
        if s.low < 0xFF000000 or s.low >= (1 << 32):
            carry = s.low >> 32
            temp = s.cache
            while True:
                s.out.append((temp + carry) & 0xFF); temp = 0xFF
                s.cache_size -= 1
                if s.cache_size == 0: break
            s.cache = (s.low >> 24) & 0xFF
        s.cache_size += 1
        s.low = (s.low & 0x00FFFFFF) << 8
    def bit(s, probs, i, b):
        p = probs[i]; bound = (s.range >> 11) * p
        if b == 0: s.range = bound; probs[i] = p + ((2048 - p) >> 5)
        else: s.low += bound; s.range -= bound; probs[i] = p - (p >> 5)
        while s.range < (1 << 24): s.range = (s.range << 8) & 0xFFFFFFFF; s.shift_low()
    def finish(s):
        for _ in range(5): s.shift_low()
        return bytes(s.out)

e = Enc(); pr = [1024] * (N * N * N)
for y in range(H):
    for x in range(W):
        l = idx[y * W + x - 1] if x else 0
        u = idx[(y - 1) * W + x] if y else 0
        v = idx[y * W + x]
        c = (l * N + u) * N
        for k in range(N - 1):                     # unary: 1 = "it is k"
            e.bit(pr, c + k, 1 if v == k else 0)
            if v == k: break
z = e.finish()

# the fire: three more frames of its region (assets/quest/rec-fire/*.png, the same video), each coded alone; the picture itself is the fourth
FX, FW, FY, FH = 44, 26, 38 - Y0, 48                 # the box in the band (x, width, row relative to the band, height)
FRAMES = sorted((A.parent / "rec-fire").glob("*.png"))
fz, fo = bytearray(), [0]
for f in FRAMES:
    fim = Image.open(f).convert("RGB").resize((W, W), Image.LANCZOS)
    fpx = fim.load()
    fidx = []
    for y in range(FY + Y0, FY + Y0 + FH):
        for x in range(FX, FX + FW):
            th = (BAYER[(y % 4) * 4 + x % 4] / 16 - 0.5) * 40
            c = fpx[x, y]
            r, g, b = (c[i] + th for i in range(3))
            fidx.append(min(range(N), key=lambda j: (r - PAL[USE[j]][0]) ** 2 * .3 + (g - PAL[USE[j]][1]) ** 2 * .59 + (b - PAL[USE[j]][2]) ** 2 * .11))
    fe = Enc(); fpr = [1024] * (N * N * N)
    for y in range(FH):
        for x in range(FW):
            l = fidx[y * FW + x - 1] if x else 0
            u = fidx[(y - 1) * FW + x] if y else 0
            v = fidx[y * FW + x]
            c = (l * N + u) * N
            for k in range(N - 1):
                fe.bit(fpr, c + k, 1 if v == k else 0)
                if v == k: break
    fz += fe.finish()
    fo.append(len(fz))
L = ["/* generated by tools/gen_quest_rec.py */", "#pragma once", "#include <stdint.h>", f"#define QREC_W {W}", f"#define QREC_H {H}", f"#define QREC_N {N}",
     "static const uint8_t QREC_PAL[QREC_N] = {" + ",".join(map(str, USE)) + "};", f"static const uint8_t QREC_Z[{len(z)}] = {{"]
L += ["    " + ",".join(str(b) for b in z[i:i + 32]) + "," for i in range(0, len(z), 32)]
L += ["};", f"#define QREC_FX {FX}", f"#define QREC_FW {FW}", f"#define QREC_FY {FY}", f"#define QREC_FH {FH}", f"#define QREC_NF {len(FRAMES)}",
      "static const uint16_t QREC_FO[QREC_NF + 1] = {" + ",".join(map(str, fo)) + "};", f"static const uint8_t QREC_FZ[{max(1, len(fz))}] = {{" + (",".join(map(str, fz)) if fz else "0") + "};"]
out.write_text("\n".join(L) + "\n")
print(f"quest rec: {W}x{H} {N} colours, {len(z)} B")
